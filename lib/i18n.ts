export type Language = (typeof supportedLanguageOptions)[number]["code"];
type UiLanguage =
  | "nl"
  | "pl"
  | "de"
  | "en"
  | "ja"
  | "hi"
  | "es"
  | "fr"
  | "zh"
  | "ko";
const priorityUiLanguages = new Set<string>([
  "nl",
  "pl",
  "de",
  "en",
  "ja",
  "hi",
  "es",
  "fr",
  "zh",
  "ko"
]);

export const supportedLanguages: readonly Language[] =
  supportedLanguageOptions.map(({ code }) => code);

export const languageLabel = (language: Language) =>
  supportedLanguageOptions.find(({ code }) => code === language)?.label ??
  language;

export const languageName = languageLabel;

export function isSupportedLanguage(value: unknown): value is Language {
  return (
    typeof value === "string" &&
    supportedLanguages.includes(value as Language)
  );
}

function uiLanguageFor(language: Language): UiLanguage {
  return priorityUiLanguages.has(language) ? (language as UiLanguage) : "en";
}

const storageKey = "jec.language";
const displayNameStorageKey = "jec.displayName";

export function getSavedLanguage(): Language | null {
  if (typeof window === "undefined") {
    return null;
  }

  const value = window.localStorage.getItem(storageKey);
  return isSupportedLanguage(value) ? value : null;
}

export function saveLanguage(language: Language) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(storageKey, language);
  }
}

export function clearSavedLanguage() {
  if (typeof window !== "undefined") {
    window.localStorage.removeItem(storageKey);
  }
}

export function normalizeDisplayName(value: string) {
  return value.trim().replace(/\s+/g, " ").slice(0, 32);
}

export function getSavedDisplayName(): string {
  if (typeof window === "undefined") {
    return "";
  }

  return normalizeDisplayName(
    window.localStorage.getItem(displayNameStorageKey) ?? ""
  );
}

export function saveDisplayName(displayName: string) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(
      displayNameStorageKey,
      normalizeDisplayName(displayName)
    );
  }
}

export function clearSavedDisplayName() {
  if (typeof window !== "undefined") {
    window.localStorage.removeItem(displayNameStorageKey);
  }
}

