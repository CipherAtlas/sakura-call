export function t(language: Language, key: TranslationKey): string {
  const uiLanguage = uiLanguageFor(language);

  if (uiLanguage === "ja") {
    return strings.ja[key] ?? strings.en[key];
  }

  if (uiLanguage === "en") {
    return strings.en[key];
  }

  return priorityUiStringOverrides[uiLanguage][key] ?? strings.en[key];
}
